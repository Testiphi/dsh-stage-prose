import { readFileSync, writeFileSync } from 'node:fs'
import { stylesheet } from '../adapters/dsh-0.2.js'
import { installSettingsPage } from '../client/settings.js'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const client = new URL('../client.js', import.meta.url)
const lf = text => text.replace(/\r\n/g, '\n')
const source = lf(`// Generated by npm run build.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    return {
      apply(ctx) {
        let retentionStyle
        function applyRetention(enabled) {
          if (!enabled) { retentionStyle?.remove(); retentionStyle = undefined; return }
          if (retentionStyle) return
          retentionStyle = document.createElement('style')
          retentionStyle.id = ${JSON.stringify(pkg.name)}
          retentionStyle.textContent = ${JSON.stringify(lf(stylesheet))}
          document.head.append(retentionStyle)
        }
        ctx.effect(() => {
          applyRetention(globalThis.__DSH_STAGE_PROSE__?.retainProse === true)
          return () => retentionStyle?.remove()
        }, 'stage-prose.styles')
        ctx.inject?.(['slots', 'locale', 'connection', 'configForms'], scope => {
          (${installSettingsPage.toString()})(scope, require('react'), applyRetention, ${JSON.stringify(lf(readFileSync(new URL('../client/settings.css', import.meta.url), 'utf8')))})
        })
      },
    }
  },
})
`)
if (process.argv.includes('--check')) {
  if (readFileSync(client, 'utf8') !== source) throw new Error('Run npm run build and commit client.js')
} else {
  writeFileSync(client, source)
}
