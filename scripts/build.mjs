import { readFileSync, writeFileSync } from 'node:fs'
import { stylesheet } from '../adapters/dsh-0.2.js'

const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'))
const client = new URL('../client.js', import.meta.url)
const source = `// Generated by npm run build.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory() {
    return {
      apply(ctx) {
        ctx.effect(() => {
          const style = document.createElement('style')
          style.id = ${JSON.stringify(pkg.name)}
          style.textContent = ${JSON.stringify(stylesheet)}
          document.head.append(style)
          return () => style.remove()
        }, 'stage-prose.styles')
      },
    }
  },
})
`
if (process.argv.includes('--check')) {
  if (readFileSync(client, 'utf8') !== source) throw new Error('Run npm run build and commit client.js')
} else {
  writeFileSync(client, source)
}
